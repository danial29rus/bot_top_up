from __future__ import annotations

from .config import Settings


def _contact(settings: Settings) -> str:
    return "встроенная поддержка в боте NovaTop"


def privacy_policy(settings: Settings) -> str:
    return f"""<b>Политика конфиденциальности</b>
Редакция от {settings.policy_revision}

{settings.operator_name} обрабатывает Telegram ID, username, имя профиля, данные заявок и обращения поддержки.

Данные нужны для заявок, ручной проверки оплаты, исполнения услуги и поддержки. Поставщику передаётся только Steam login или username получателя, необходимые для услуги.

Пароли, коды входа и реквизиты карт не запрашиваются. Доступ к базе и ключам поставщика ограничен.

Плановый срок хранения — до {settings.data_retention_days} дней после операции, если иной срок не требуется законом. Запросить сведения, исправление или удаление можно через {_contact(settings)}."""


def terms_of_service(settings: Settings) -> str:
    return f"""<b>Пользовательское соглашение</b>
Редакция от {settings.policy_revision}

Бот принимает заявки на цифровые услуги. Нажатие «Я оплатил(а)» не означает подтверждения оплаты: её проверяет владелец сервиса.

Пользователь отвечает за точность Steam login и Telegram username и не указывает чужие аккаунты без права на это. Пароли и коды входа отправлять запрещено.

После подтверждения оплаты заявка передаётся поставщику. Статус «Выполнен» в личном кабинете означает завершение услуги. В заявке могут отказать из-за ошибочных данных, ограничений региона, отсутствия товара или нарушения правил платформы.

Поддержка: {_contact(settings)}. Нажатие «Принимаю» означает согласие с условиями и политикой конфиденциальности."""


def payment_and_refunds(settings: Settings) -> str:
    return f"""<b>Оплата, отмена и возвраты</b>
Редакция от {settings.policy_revision}

<b>Оплата</b>
Сумма и доступный способ оплаты отображаются в заявке. До оплаты проверьте номер, услугу и данные получателя.

<b>Отмена до исполнения</b>
Напишите в {_contact(settings)} с номером заявки. Отмена возможна, пока заказ не передан поставщику.

<b>Ошибочные данные</b>
Повторная выдача не производится, если услуга доставлена на данные пользователя. Ошибку поставщика проверит Оператор.

<b>Возврат</b>
Если поставщик не смог выполнить заявку, порядок возврата согласуется через поддержку после проверки. Срок и способ зависят от исходной оплаты и закона."""


def service_rules(settings: Settings) -> str:
    return f"""<b>Правила сервиса</b>

• Проверяйте данные получателя до оплаты.
• Не используйте сервис для действий, нарушающих закон или правила Steam/Telegram.
• Не передавайте пароли, коды подтверждения, резервные коды и ключи API.
• Статус заявки и история доступны в разделе «Личный кабинет».
• Вопросы по заявке решаются по её номеру через {_contact(settings)}.

Оператор: {settings.operator_name}"""
